// 依据：谭其骧《中国历史地图集》第一册「商时期全图」经纬网格配准读图
// （lon=(x−1385.4)/58.33+102.5, lat=45−(y−115)/66；殷/周双锚点验证误差<0.15°）。
// 谭图本幅不画疆域色块，此多边形为「商据点群（殷/亳/邢/周/盘龙城/徐州/济南等）
// + 四土范围注记」的推定示意包络，页脚口径=学界推定示意。
// 航点顺时针：西（陇山—秦岭—大巴—荆山）→ 南（汉水—盘龙城—大别）→
//             东（淮泗—徐州—泰山西麓—济南）→ 北（冀中—太行）→ 晋南—渭北回线
import { writeFileSync } from 'node:fs';

const WAYPOINTS = [
  [106.45, 35.40], // 陇山东侧（西北角）
  [106.70, 34.50], [107.10, 33.70], [108.00, 33.10], // 泾渭西缘—秦岭
  [108.90, 32.50], [110.30, 31.90], [111.80, 32.10], // 大巴山—荆山（楚在界外）
  [113.20, 31.60], [114.20, 30.65], // 随枣走廊—盘龙城（南土极点）
  [115.10, 30.70], [115.90, 31.70], [116.20, 32.60], // 大别山东麓北上
  [116.90, 33.40], [117.40, 34.30], // 淮泗—徐州（东土）
  [117.30, 35.30], [117.40, 36.20], [117.00, 36.85], // 鲁西南—泰山西麓—济南城子崖
  [116.40, 37.20], [115.70, 37.80], [114.90, 38.30], // 濟水下游—憈沱—沙丘
  [114.10, 38.55], [113.60, 38.35], // 冀中北限（燕山南麓方国在界外）
  [112.90, 38.00], [112.30, 37.60], // 太行西麓—太原盆地（唐）
  [111.90, 37.00], [111.20, 36.80], [110.70, 36.20], // 吕梁—晋中
  [110.30, 35.60], [110.60, 34.90], // 晋南（运城—平陆）
  [109.80, 34.60], [108.50, 35.00], [107.30, 35.30], // 渭北回线（周原在界内）
];

// Catmull-Rom 平滑闭合环
const smoothClosed = (pts, seg = 4) => {
  const n = pts.length;
  const out = [];
  for (let i = 0; i < n; i++) {
    const p0 = pts[(i - 1 + n) % n], p1 = pts[i], p2 = pts[(i + 1) % n], p3 = pts[(i + 2) % n];
    for (let t = 0; t < seg; t++) {
      const u = t / seg, u2 = u * u, u3 = u2 * u;
      out.push([
        0.5 * (2 * p1[0] + (-p0[0] + p2[0]) * u + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * u2 + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * u3),
        0.5 * (2 * p1[1] + (-p0[1] + p2[1]) * u + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * u2 + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * u3),
      ]);
    }
  }
  out.push(out[0]); // 闭合
  return out;
};

const ring = smoothClosed(WAYPOINTS).map(([lon, lat]) => [
  Math.round(lon * 100) / 100, Math.round(lat * 100) / 100,
]);

const fc = {
  type: 'FeatureCollection',
  features: [{
    type: 'Feature',
    properties: {
      name: '__dynasty__', layer: 'dynasty',
      source: '谭其骧《中国历史地图集》第一册·商时期全图（网格配准读图，据点群推定示意）',
    },
    geometry: { type: 'MultiPolygon', coordinates: [[ring]] },
  }],
};
writeFileSync(new URL('./hand-shang.json', import.meta.url), JSON.stringify(fc));
console.log(`hand-shang.json: ${ring.length} 点`);
